import type { SnapshotSummary } from "../../api/types";
import { CollectionBadge, SyntheticBadge } from "../../components/Badge";
import { Notice } from "../../components/Feedback";
import { DateTime, WindowRange } from "../../components/Time";
import { collectionStatusLabel } from "../../lib/classification";
import { displayValue, shortHash } from "../../lib/format";

/** What was collected (counts and per-modality outcomes); failures first and prominent. */
export function CollectionSummary({ snapshot }: { snapshot: SnapshotSummary }) {
  const problems = snapshot.collection.filter((c) => c.status !== "ok");
  const ordered = [...problems, ...snapshot.collection.filter((c) => c.status === "ok")];
  const redaction = Object.entries(snapshot.redaction ?? {});
  return (
    <div className="collection">
      {snapshot.synthetic ? (
        <p>
          <SyntheticBadge /> This snapshot was generated by a synthetic scenario, not collected from
          your systems.
        </p>
      ) : null}
      {problems.length ? (
        <Notice tone="error" title="Some telemetry was not collected" role="alert">
          <ul>
            {problems.map((c, i) => (
              <li key={i}>
                <strong>{c.modality}</strong> from {c.provider}: {collectionStatusLabel(c.status)}
                {c.detail ? ` — ${c.detail}` : ""}
              </li>
            ))}
          </ul>
          <p className="small">The analysis treats missing telemetry as a coverage gap, not as healthy.</p>
        </Notice>
      ) : null}
      <dl className="stat-row">
        {Object.entries(snapshot.counts).map(([k, v]) => (
          <div key={k} className="stat">
            <dt>{k}</dt>
            <dd>{v.toLocaleString()}</dd>
          </div>
        ))}
      </dl>
      <div className="table-wrap">
        <table className="table table-compact">
          <caption className="visually-hidden">Collection outcome per modality</caption>
          <thead>
            <tr>
              <th scope="col">Modality</th>
              <th scope="col">Provider</th>
              <th scope="col">Outcome</th>
              <th scope="col" className="num">
                Items
              </th>
              <th scope="col">Detail</th>
            </tr>
          </thead>
          <tbody>
            {ordered.map((c, i) => (
              <tr key={i} className={c.status !== "ok" ? "row-problem" : undefined}>
                <td>{c.modality}</td>
                <td>{c.provider}</td>
                <td>
                  <CollectionBadge status={c.status} />
                  {c.truncated ? <span className="badge warn">truncated</span> : null}
                </td>
                <td className="num">{c.items.toLocaleString()}</td>
                <td>{c.detail || <span className="muted">—</span>}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <dl className="kv kv-compact">
        {snapshot.collected_window ? (
          <div className="kv-row">
            <dt>Collected window</dt>
            <dd>
              <WindowRange start={snapshot.collected_window.start} end={snapshot.collected_window.end} />
            </dd>
          </div>
        ) : null}
        <div className="kv-row">
          <dt>Captured</dt>
          <dd>
            <DateTime value={snapshot.captured_at} />
          </dd>
        </div>
        <div className="kv-row">
          <dt>Digest</dt>
          <dd>
            <code title={snapshot.digest}>{shortHash(snapshot.digest, 20)}</code>
          </dd>
        </div>
        <div className="kv-row">
          <dt>Redaction</dt>
          <dd>
            {redaction.length
              ? redaction.map(([k, v]) => `${k}: ${displayValue(v)}`).join(" · ")
              : "—"}
          </dd>
        </div>
      </dl>
    </div>
  );
}
