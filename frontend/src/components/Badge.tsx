import {
  checkStateLabel,
  checkTone,
  collectionStatusLabel,
  presentClassification,
  supportLabel,
} from "../lib/classification";
import { capitalize, humanize } from "../lib/format";

// Class names are chosen from fixed sets; API values never become class names directly.

const SEVERITY = new Set(["critical", "high", "medium", "low", "info"]);
const INCIDENT_STATUS = new Set(["open", "investigating", "resolved", "closed"]);
const INVESTIGATION_STATUS = new Set(["queued", "running", "completed", "failed", "cancelled"]);
const SUPPORT = new Set(["strong", "moderate", "weak", "none"]);
const COLLECTION = new Set(["ok", "partial", "failed", "not_configured"]);

function known(set: Set<string>, value: string | null | undefined): string {
  return value && set.has(value) ? value : "unknown";
}

export function SeverityBadge({ severity }: { severity: string }) {
  return <span className={`badge sev sev-${known(SEVERITY, severity)}`}>{severity}</span>;
}

export function IncidentStatusBadge({ status }: { status: string }) {
  return (
    <span className={`badge ist ist-${known(INCIDENT_STATUS, status)}`}>{capitalize(status)}</span>
  );
}

export function InvestigationStatusBadge({ status }: { status: string }) {
  return (
    <span className={`badge vst vst-${known(INVESTIGATION_STATUS, status)}`}>
      {capitalize(status)}
    </span>
  );
}

export function SyntheticBadge({ compact = false }: { compact?: boolean }) {
  return (
    <span
      className="badge synthetic"
      title="Generated by a synthetic benchmark scenario, not collected from your systems"
    >
      {compact ? "SYNTHETIC" : "SYNTHETIC DATA"}
    </span>
  );
}

export function VerdictBadge({ classification }: { classification: string | null | undefined }) {
  const p = presentClassification(classification);
  return <span className={`badge verdict verdict-${p.tone}`}>{p.label}</span>;
}

export function SupportBadge({ support }: { support: string | null | undefined }) {
  return (
    <span
      className={`badge support support-${known(SUPPORT, support)}`}
      title="Support is an ordinal level (strong > moderate > weak > none), not a probability"
    >
      Support: {supportLabel(support)}
    </span>
  );
}

export function CheckBadge({ state }: { state: string }) {
  return <span className={`badge check check-${checkTone(state)}`}>{checkStateLabel(state)}</span>;
}

export function CollectionBadge({ status }: { status: string }) {
  return (
    <span className={`badge coll coll-${known(COLLECTION, status)}`}>
      {collectionStatusLabel(status)}
    </span>
  );
}

export function NeutralBadge({ children }: { children: string }) {
  return <span className="badge neutral">{humanize(children)}</span>;
}
